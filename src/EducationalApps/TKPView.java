    private void NilaiMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_NilaiMouseClicked
        // TODO add your handling code here:
        boolean running = true;

        while (running) {
            int nilaiSoal = 0;

            if (benar1.isSelected()) {
                nilaiSoal++;
            } else if (saa.isSelected()) {
                nilaiSoal++;
            } else if (benar3.isSelected()) {
                nilaiSoal++;
            } else if (asdasda.isSelected()) {
                nilaiSoal++;
            } else {
            }

            nilaiSoal(nilaiSoal);

            int as = JOptionPane.showConfirmDialog(this, "Apakah Kamu Ingin Mengerjakannya lagi??");

            if (as == 0) {
                running = false;
                TWKView in = new TWKView();
                in.setVisible(true);

            } else if (as == 1) {
                running = false;
                MainView in = new MainView();
                in.setVisible(true);
            }
        }

    }//GEN-LAST:event_NilaiMouseClicked

