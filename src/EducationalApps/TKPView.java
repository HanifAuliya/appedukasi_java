    public static int nilaiSoal(int nilaiSoal) {
        int hasil;
        hasil = nilaiSoal * 25;
        Component frame = null;

        JOptionPane.showMessageDialog(frame, "Benar = " + nilaiSoal + "  Salah = " + (4 - nilaiSoal));
        JOptionPane.showMessageDialog(frame, "Nilai Kamu adalah " + hasil);

        return hasil;
    }
    
